import { defineConfig, type InputTransformerFn } from "orval";

// Generates the API client from the pinned OpenAPI document
// (docs/architecture.md, Backend Contract and API Client Generation). Run it
// with `scripts/tooling.sh generate`; never edit its output by hand.

// The prefix of the operations that the UI calls (Sentinel docs/api-spec.md,
// Base URL). The document also describes the probes /health and /ready, which
// the Sentinel host does not route to the API.
const API_PREFIX = "/api/v1/";

const METHODS = ["get", "put", "post", "delete", "options", "head", "patch"];

// Sentinel's operationIds are FastAPI's defaults: the handler name, then the
// path with every character other than a letter, digit, or "_" replaced by
// "_", then the method, such as list_tickets_api_v1_tickets_get. The client
// names each operation after its handler, such as listTickets.
function handlerName(operationId: string, path: string, method: string) {
  const suffix = `${path.replaceAll(/\W/g, "_")}_${method}`;
  return operationId.length > suffix.length && operationId.endsWith(suffix)
    ? operationId.slice(0, -suffix.length)
    : operationId;
}

// Keeps only the operations under API_PREFIX and shortens their operationIds.
// Fails when two operations would get the same name.
const sentinelOperations: InputTransformerFn = (document) => {
  const names = new Set<string>();
  const paths = Object.fromEntries(
    Object.entries(document.paths ?? {}).filter(([path]) =>
      path.startsWith(API_PREFIX),
    ),
  );
  for (const [path, item] of Object.entries(paths)) {
    for (const [method, operation] of Object.entries(item ?? {})) {
      if (
        !METHODS.includes(method) ||
        typeof operation !== "object" ||
        operation === null ||
        !("operationId" in operation) ||
        typeof operation.operationId !== "string"
      ) {
        continue;
      }
      const name = handlerName(operation.operationId, path, method);
      if (names.has(name)) {
        throw new Error(`Two operations of the document are named ${name}`);
      }
      names.add(name);
      operation.operationId = name;
    }
  }
  return { ...document, paths };
};

export default defineConfig({
  sentinel: {
    input: {
      target: "./contract/sentinel.openapi.json",
      override: { transformer: sentinelOperations },
    },
    output: {
      target: "./src/api/generated/sentinel.ts",
      schemas: "./src/api/generated/model",
      mode: "tags",
      client: "react-query",
      httpClient: "fetch",
      namingConvention: "kebab-case",
      urlEncodeParameters: true,
      clean: true,
      formatter: "prettier",
      override: {
        // Without the document's version, which would change every file on
        // each change of the pinned Sentinel version.
        header: () => [
          "Generated by Orval from contract/sentinel.openapi.json.",
          "Do not edit by hand: run `scripts/tooling.sh generate`.",
        ],
        mutator: { path: "./src/api/request.ts", name: "apiRequest" },
        // The request functions return the body; apiRequest throws on errors.
        fetch: { includeHttpResponseReturnType: false },
      },
    },
  },
});
